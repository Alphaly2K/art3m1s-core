#!/usr/bin/env python3
"""Generate C# declarations from the Artemis v2 C header."""

import argparse
import json
from pathlib import Path
import re
import subprocess

DIRECTORY = Path(__file__).resolve().parent
HEADER = DIRECTORY.parents[2] / 'doc/abi/art3m1s_core_v2.draft.h'
OUTPUT = DIRECTORY / 'ArtemisNative.g.cs'

PRIMITIVES = {
    'void': 'void', 'int32_t': 'int', 'int64_t': 'long',
    'uint8_t': 'byte', 'uint16_t': 'ushort', 'uint32_t': 'uint', 'uint64_t': 'ulong',
}


def clang(*args):
    return subprocess.check_output(['clang', '-x', 'c', *args, str(HEADER)], text=True)


def managed_type(ctype, types):
    pointer = re.fullmatch(r'(.+?)\s*\(\*\)\((.*)\)', ctype)
    if pointer:
        result, arguments = pointer.groups()
        signature = [managed_type(item.strip(), types) for item in arguments.split(',')]
        signature.append(managed_type(result, types))
        return 'delegate* unmanaged[Cdecl]<' + ', '.join(signature) + '>'
    plain = ctype.removeprefix('const ').replace('*', '').strip()
    return types[plain] + '*' * ctype.count('*')


def constant(name, expression):
    if expression == 'UINT32_MAX':
        return f'    public const uint {name} = uint.MaxValue;'
    match = re.fullmatch(r'(\(-)?(U?INT)(16|32|64)_C\((0x[0-9A-Fa-f]+|[0-9]+)\)(?(1)\))', expression)
    if match is None:
        raise ValueError(f'Unsupported macro {name}: {expression}')
    negative, signedness, width, value = match.groups()
    ctype = PRIMITIVES[signedness.lower() + width + '_t']
    suffix = {'uint': 'u', 'ulong': 'ul', 'long': 'L'}.get(ctype, '')
    sign = '-' if negative else ''
    return f'    public const {ctype} {name} = {sign}{value}{suffix};'


def generate():
    declarations = json.loads(clang('-Xclang', '-ast-dump=json', '-fsyntax-only'))['inner']
    records = [node for node in declarations if node['kind'] == 'RecordDecl'
               and node.get('name', '').startswith('Art') and node.get('completeDefinition')]
    types = PRIMITIVES | {node['name']: node['name'] for node in records}
    for node in declarations:
        if node['kind'] == 'TypedefDecl' and node['name'].startswith('Art') and node['name'] not in types:
            types[node['name']] = managed_type(node['type']['qualType'], types)

    lines = [
        '// Generated by generate.py from doc/abi/art3m1s_core_v2.draft.h.',
        'using System.Runtime.InteropServices;', '', 'namespace Artemis.Host', '{',
    ]
    body = []
    for record in records:
        if record['tagUsed'] != 'struct':
            raise ValueError(f'Unsupported record: {record["name"]}')
        body += ['[StructLayout(LayoutKind.Sequential)]', f'public unsafe struct {record["name"]}', '{']
        for field in record['inner']:
            if field['kind'] != 'FieldDecl' or field.get('isBitfield'):
                raise ValueError(f'Unsupported member in {record["name"]}: {field["kind"]}')
            body.append(f'    public {managed_type(field["type"]["qualType"], types)} {field["name"]};')
        body += ['}', '']

    body += ['public static unsafe class ArtemisNative', '{']
    for macro in sorted(clang('-dM', '-E').splitlines()):
        match = re.fullmatch(r'#define (ART_\w+) (?P<expression>.+)', macro)
        if match:
            body.append(constant(*match.groups()))

    for node in declarations:
        if node['kind'] != 'FunctionDecl' or not node.get('name', '').startswith('art3m1s_'):
            continue
        result = managed_type(node['type']['qualType'].split(' (', 1)[0], types)
        parameters = ', '.join(
            f'{managed_type(parameter["type"]["qualType"], types)} {parameter["name"]}'
            for parameter in node['inner'] if parameter['kind'] == 'ParmVarDecl'
        )
        body += ['', '    [DllImport("art3m1s_core", CallingConvention = CallingConvention.Cdecl, ExactSpelling = true)]',
                 f'    public static extern {result} {node["name"]}({parameters});']
    body.append('}')
    return '\n'.join(lines + ['    ' + line if line else '' for line in body] + ['}', ''])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='check the committed output')
    args = parser.parse_args()
    generated = generate()
    if args.check:
        if generated != OUTPUT.read_text(encoding='utf-8'):
            parser.exit(1, 'Run generate.py to refresh the C# bindings.\n')
    else:
        OUTPUT.write_text(generated, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
